  0x03, 0x03, 0x02, 0x00, 0x01, // Functions
  0x07, 0x2b, 0x02,
  0x11, 0x63, 0x61, 0x6c, 0x63, 0x5f, 0x63, 0x6f, 0x6c, 0x75, 0x6d, 0x6e, 0x5f, 0x77, 0x69, 0x64, 0x74, 0x68, 0x00, 0x00, // calc_column_width
  0x10, 0x63, 0x61, 0x6c, 0x63, 0x5f, 0x63, 0x61, 0x72, 0x64, 0x5f, 0x68, 0x65, 0x69, 0x67, 0x68, 0x74, 0x00, 0x01, // calc_card_height
